// Splices the tsrs transpile engine into a Node.JS+ lib/internal/modules/cjs/loader.js, behind a TS_ENGINE switch.
//   node make-splice.cjs <loader.js> [path-to-wasm]
// Inserts (idempotently, between // TSRS-BEGIN and // TSRS-END markers) right before the line that starts with
// `transpiler.babel=`: keeps the TS6 bundle as transpiler.typescript6 and replaces transpiler.typescript with a Proxy
// that serves transpileModule()/transpile() from the tsrs wasm when process.env.TS_ENGINE === 'tsrs' (checked per call,
// like DS_ENGINE), otherwise from TS6. The wasm (brotli+base64) is only decoded/compiled on first use.
const fs = require('fs'), zlib = require('zlib');
const loaderPath = process.argv[2];
const wasmPath = process.argv[3] || require('path').join(__dirname, '..', 'dist', 'tsrs_transpile.wasm');
if (!loaderPath) { console.error('usage: node make-splice.cjs <loader.js> [wasm]'); process.exit(2); }
const br = zlib.brotliCompressSync(fs.readFileSync(wasmPath), { params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 11 } });
const BS = String.fromCharCode(92);
const NUL = BS + '0', NL = BS + 'n';
const snippet = [
'// TSRS-BEGIN (generated by tools/make-splice.cjs - do not edit by hand)',
'transpiler.typescript6=transpiler.typescript;',
'transpiler.typescript=(function(){',
'  const WASM_B64=\'' + br.toString('base64') + '\';',
'  let mod=null;',
'  function getModule(){',
'    if(mod)return mod;',
'    mod=new WebAssembly.Module(require(\'zlib\').brotliDecompressSync(Buffer.from(WASM_B64,\'base64\')));',
'    return mod;',
'  }',
'  function run(fileName,options,src){',
'    let mem;',
'    const dv=()=>new DataView(mem.buffer);',
'    const wasi=new Proxy({',
'      random_get(p,l){const u=new Uint8Array(mem.buffer,p,l);for(let i=0;i<l;i++)u[i]=(Math.random()*256)|0;return 0;},',
'      clock_time_get(id,prec,o){dv().setBigUint64(o,BigInt(Date.now())*1000000n,true);return 0;},',
'      environ_sizes_get(a,b){dv().setUint32(a,0,true);dv().setUint32(b,0,true);return 0;},',
'      environ_get(){return 0;},',
'      fd_write(fd,iov,n,w){let t=0;for(let i=0;i<n;i++)t+=dv().getUint32(iov+i*8+4,true);dv().setUint32(w,t,true);return 0;},',
'      fd_fdstat_get(){return 8;},fd_prestat_get(){return 8;},fd_close(){return 8;},',
'      proc_exit(c){throw new Error(\'tsrs wasm exit \'+c);},',
'    },{get:(o,k)=>o[k]||(()=>52)});',
'    const inst=new WebAssembly.Instance(getModule(),{tsrs_host:{fs:()=>-1,fs_take(){}},wasi_snapshot_preview1:wasi});',
'    mem=inst.exports.memory;',
'    const req=Buffer.from([fileName,JSON.stringify(options||{}),src].join(\'' + NUL + '\'));',
'    {const ptr=inst.exports.tsrs_input(req.length);new Uint8Array(mem.buffer).set(req,ptr);}',
'    const st=inst.exports.tsrs_transpile();',
'    const out=Buffer.from(mem.buffer,inst.exports.tsrs_output(),inst.exports.tsrs_output_len()).toString();',
'    if(st===0){const sm=Buffer.from(mem.buffer,inst.exports.tsrs_map(),inst.exports.tsrs_map_len()).toString();const r={outputText:out,diagnostics:[]};if(sm!==\'\')r.sourceMapText=sm;return r;}',
'    const i=out.indexOf(\'' + NUL + '\');',
'    if(i<0)throw new Error(\'tsrs transpile: \'+out);',
'    // syntax errors: like ts.transpile(), emit what we have; transpileModule(..,{reportDiagnostics:true}) callers get them',
'    const parse=(m)=>{const p=m.indexOf(" TS"),q=m.indexOf(": ",p);if(p>0&&q>p){const lc=m.slice(0,p).split(":");return {category:1,line:+lc[0],character:+lc[1],code:+m.slice(p+3,q),messageText:m.slice(q+2)};}return {category:1,messageText:m};};',
'    return {outputText:out.slice(i+1),diagnostics:out.slice(0,i).split(\'' + NL + '\').map(parse)};',
'  }',
'  const tsrsApi={',
'    transpileModule(src,opts){opts=opts||{};return run(opts.fileName||\'\',opts.compilerOptions,src);},',
'    transpile(src,compilerOptions,fileName){return run(fileName||\'\',compilerOptions,src).outputText;},',
'  };',
'  const useTsrs=()=>global.process.env.TS_ENGINE===\'tsrs\';',
'  return new Proxy(transpiler.typescript6,{get(target,prop){',
'    if(useTsrs()&&Object.prototype.hasOwnProperty.call(tsrsApi,prop))return tsrsApi[prop];',
'    return target[prop];',
'  }});',
'}());',
'// tsCheck(result, file, directiveLine): throws a SyntaxError listing the syntax errors; for a #ts block directiveLine is the',
'// 1-based line of the #ts directive, so reported lines are file lines (nested-directive expansion inside a block can shift them)',
'transpiler.tsCheck=function(r,file,directiveLine){',
'  const ds=(r.diagnostics||[]).filter((d)=>d.category===1);',
'  if(!ds.length)return r;',
'  const ts=transpiler.typescript6,nl=String.fromCharCode(10),off=directiveLine||0;',
'  const flat=(m)=>typeof m==="string"?m:ts.flattenDiagnosticMessageText(m,nl);',
'  const lines=ds.map((d)=>{',
'    if(d.line!==undefined)return (d.line+off)+":"+d.character+" TS"+d.code+": "+d.messageText;',
'    if(!d.file)return flat(d.messageText);',
'    const lc=d.file.getLineAndCharacterOfPosition(d.start||0);',
'    return (lc.line+1+off)+":"+(lc.character+1)+" TS"+d.code+": "+flat(d.messageText);',
'  });',
'  const hdr=file?file+": "+lines.length+" syntax error(s)":"#ts block at line "+off+": "+lines.length+" syntax error(s)";',
'  const err=new SyntaxError(hdr+nl+lines.join(nl));',
'  Object.defineProperty(err,"tsBlockError",{value:true});',
'  throw err;',
'};',
'// TSRS-END',
''].join('\n');
let text = fs.readFileSync(loaderPath, 'utf8');
const nl = text.includes('\r\n') ? '\r\n' : '\n';
const b = text.indexOf('// TSRS-BEGIN'), e = text.indexOf('// TSRS-END');
if (b >= 0 && e > b) {
  const endLine = text.indexOf('\n', e) + 1;
  text = text.slice(0, b) + text.slice(endLine);
}
const anchor = text.indexOf('transpiler.babel=(function');
if (anchor < 0 || text[anchor - 1] !== '\n') { console.error('anchor `transpiler.babel=(function` not found at line start'); process.exit(1); }
text = text.slice(0, anchor) + snippet.replace(/\n/g, nl) + text.slice(anchor);
const sites = [
  ['typescript.transpileModule(code, {compilerOptions:{sourceMap: true}});',
   'transpiler.tsCheck(typescript.transpileModule(code, {reportDiagnostics:true, compilerOptions:{sourceMap: true}}), undefined, endCode.tsLine);'],
  ['return ctx.transpiler.typescript.transpileModule(preprocessed, {}).outputText;',
   'return transpiler.tsCheck(ctx.transpiler.typescript.transpileModule(preprocessed, {reportDiagnostics:true}), undefined, node.startLine).outputText;'],
  // AST engine: remember the line of the #ts / #cs directive
  ['openBlock = { kind: kw, rawLines: [] };',
   'openBlock = { kind: kw, rawLines: [], startLine: absLine };'],
  ['content = transpiler.typescript.transpile(content);',
   'content = transpiler.tsCheck(transpiler.typescript.transpileModule(content, {reportDiagnostics:true}), filename).outputText;'],
];
for (const [from, to] of sites) {
  if (text.includes(to)) continue;
  if (!text.includes(from)) { console.error('call site not found: ' + from); process.exit(1); }
  text = text.replace(from, to);
}
{ // default engine: remember the line of the #ts directive for endCode()
  const re = /else if \(key === 'ts'\)(\s*)\{(\s*)\+\+srcLineNum;/;
  const marker = 'endCode.tsLine = ';
  if (!text.includes(marker)) {
    if (!re.test(text)) { console.error("expand() key === 'ts' branch not found"); process.exit(1); }
    text = text.replace(re, (m, a, b) => "else if (key === 'ts')" + a + '{' + b + marker + 's.slice(0, match.index).split(String.fromCharCode(10)).length;' + b + '++srcLineNum;');
  }
}
{ // default D Script engine: expand()'s catch-all turns every error into "//d: unspecified error, abort!" - let ours through
  const re = /catch \(ex\)(\s*)\{(\s*)pushLine\(INFO_ABORT\);/;
  const marker = 'if (ex && ex.tsBlockError) throw ex;';
  if (!text.includes(marker)) {
    if (!re.test(text)) { console.error('expand() catch not found'); process.exit(1); }
    text = text.replace(re, (m, a, b) => 'catch (ex)' + a + '{' + b + marker + b + 'pushLine(INFO_ABORT);');
  }
}
fs.writeFileSync(loaderPath, text);
console.log('spliced', loaderPath, 'wasm brotli bytes', br.length, 'snippet chars', snippet.length);
