// Generates a src_packs-style drop-in: global.transpiler.typescript backed by the tsrs wasm (TS7-lineage compiler).
//   node make-pack.cjs [wasm] [outFile]
// Same convention as src_packs/ts/*/TypeScript.packed.js (assigns global.transpiler.typescript). Usable two ways:
//   * runtime, on any Node.JS+ with global.transpiler (v26.x): node -r ./TypeScript.packed.js app.ds   (or NODE_OPTIONS=--require=...)
//   * spliced into loader.js in place of the bundled TS6 (like the other packs).
// Call sites in loader.js ignore diagnostics, so syntax errors are WARNED on stderr (code is still emitted) unless the caller
// asks for reportDiagnostics. TSRS_QUIET=1 silences the warning. The wasm is decoded/compiled lazily on first use.
const fs = require('fs'), zlib = require('zlib');
const wasmPath = process.argv[2] || require('path').join(__dirname, '..', 'dist', 'tsrs_transpile.wasm');
const out = process.argv[3] || 'TypeScript.packed.js';
const br = zlib.brotliCompressSync(fs.readFileSync(wasmPath), { params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 11 } });
const BS = String.fromCharCode(92), NUL = BS + '0', NL = BS + 'n';
const code = [
'// tsrs (Rust port of the TypeScript 7 compiler, Apache-2.0, github.com/oxc-project/tsrs) single-file transpile as WebAssembly.',
'// Modified for Node.JS+ (adds a transpile export). Licences: LICENSE.tsrs / NOTICE.tsrs next to this file. Generated by tools/make-pack.cjs.',
'function dummy(s) {return s;}',
'global.transpiler ??= {};',
'global.transpiler.typescript=(function() {',
'  const WASM_B64=\'' + br.toString('base64') + '\';',
'  let mod=null;',
'  function getModule(){',
'    if(mod)return mod;',
'    mod=new WebAssembly.Module(require(\'zlib\').brotliDecompressSync(Buffer.from(WASM_B64,\'base64\')));',
'    return mod;',
'  }',
'  function run(fileName,options,src){',
'    let mem;',
'    const dv=()=>new DataView(mem.buffer);',
'    const wasi=new Proxy({',
'      random_get(p,l){const u=new Uint8Array(mem.buffer,p,l);for(let i=0;i<l;i++)u[i]=(Math.random()*256)|0;return 0;},',
'      clock_time_get(id,prec,o){dv().setBigUint64(o,BigInt(Date.now())*1000000n,true);return 0;},',
'      environ_sizes_get(a,b){dv().setUint32(a,0,true);dv().setUint32(b,0,true);return 0;},',
'      environ_get(){return 0;},',
'      fd_write(fd,iov,n,w){let t=0;for(let i=0;i<n;i++)t+=dv().getUint32(iov+i*8+4,true);dv().setUint32(w,t,true);return 0;},',
'      fd_fdstat_get(){return 8;},fd_prestat_get(){return 8;},fd_close(){return 8;},',
'      proc_exit(c){throw new Error(\'tsrs wasm exit \'+c);},',
'    },{get:(o,k)=>o[k]||(()=>52)});',
'    const inst=new WebAssembly.Instance(getModule(),{tsrs_host:{fs:()=>-1,fs_take(){}},wasi_snapshot_preview1:wasi});',
'    mem=inst.exports.memory;',
'    const req=Buffer.from([fileName,JSON.stringify(options||{}),src].join(\'' + NUL + '\'));',
'    {const ptr=inst.exports.tsrs_input(req.length);new Uint8Array(mem.buffer).set(req,ptr);}',
'    const st=inst.exports.tsrs_transpile();',
'    const out=Buffer.from(mem.buffer,inst.exports.tsrs_output(),inst.exports.tsrs_output_len()).toString();',
'    if(st===0){const sm=Buffer.from(mem.buffer,inst.exports.tsrs_map(),inst.exports.tsrs_map_len()).toString();const r={outputText:out,diagnostics:[]};if(sm!==\'\')r.sourceMapText=sm;return r;}',
'    const i=out.indexOf(\'' + NUL + '\');',
'    if(i<0)throw new Error(\'tsrs transpile: \'+out);',
'    const msgs=out.slice(0,i).split(\'' + NL + '\');',
'    return {outputText:out.slice(i+1),diagnostics:msgs.map((m)=>({messageText:m,category:1})),syntaxErrors:msgs};',
'  }',
'  function finish(r,opts,fileName){',
'    if(r.syntaxErrors){',
'      if(!(opts&&opts.reportDiagnostics)&&!global.process.env.TSRS_QUIET)',
'        console.error("[tsrs] "+(fileName||"#ts block")+": "+r.syntaxErrors.length+" syntax error(s) (line:col relative to the code compiled):"+String.fromCharCode(10)+r.syntaxErrors.join(String.fromCharCode(10)));',
'      delete r.syntaxErrors;',
'    }',
'    if(r.sourceMapText===undefined||r.sourceMapText===\'\')delete r.sourceMapText;',
'    return r;',
'  }',
'  return {',
'    transpileModule(src,opts){opts=opts||{};return finish(run(opts.fileName||\'\',opts.compilerOptions,src),opts,opts.fileName);},',
'    transpile(src,compilerOptions,fileName){return finish(run(fileName||\'\',compilerOptions,src),null,fileName).outputText;},',
'  };',
'}());',
''].join('\n');
fs.writeFileSync(out, code);
console.log('wrote', out, 'bytes', code.length, '(wasm brotli', br.length + ')');
