// Generates tsrs-ts-shim.js: a self-contained drop-in for global.transpiler.typescript backed by the tsrs_transpile
// wasm (brotli+base64 embedded). Mimics what would be spliced into loader.js: uses only WebAssembly, Buffer,
// require('zlib') (lazy), Math.random and Date - no node_modules, no fs, no worker threads.
// usage: node make-embed.cjs [path-to-wasm] [out.js]
const fs = require('fs'), zlib = require('zlib');
const wasmPath = process.argv[2] || require('path').join(__dirname, '..', 'dist', 'tsrs_transpile.wasm');
const out = process.argv[3] || 'tsrs-ts-shim.js';
const br = zlib.brotliCompressSync(fs.readFileSync(wasmPath), { params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 11 } });
const b64 = br.toString('base64');
const code = `// generated by make-embed.cjs - do not edit
(function () {
  const WASM_B64 = '${b64}';
  let mod = null;
  function getModule() {
    if (mod) return mod;
    const raw = require('zlib').brotliDecompressSync(Buffer.from(WASM_B64, 'base64'));
    mod = new WebAssembly.Module(raw);
    return mod;
  }
  function run(fileName, options, src) {
    let mem;
    const dv = () => new DataView(mem.buffer);
    const wasi = new Proxy({
      random_get(p, l) { const u = new Uint8Array(mem.buffer, p, l); for (let i = 0; i < l; i++) u[i] = (Math.random() * 256) | 0; return 0; },
      clock_time_get(id, prec, o) { dv().setBigUint64(o, BigInt(Date.now()) * 1000000n, true); return 0; },
      environ_sizes_get(a, b) { dv().setUint32(a, 0, true); dv().setUint32(b, 0, true); return 0; },
      environ_get() { return 0; },
      fd_write(fd, iov, n, w) { let t = 0; for (let i = 0; i < n; i++) t += dv().getUint32(iov + i * 8 + 4, true); dv().setUint32(w, t, true); return 0; },
      fd_fdstat_get() { return 8; }, fd_prestat_get() { return 8; }, fd_close() { return 8; },
      proc_exit(c) { throw new Error('tsrs wasm exit ' + c); },
    }, { get: (o, k) => o[k] || (() => 52) });
    const inst = new WebAssembly.Instance(getModule(), { tsrs_host: { fs: () => -1, fs_take() {} }, wasi_snapshot_preview1: wasi });
    mem = inst.exports.memory;
    const req = Buffer.from([fileName, JSON.stringify(options || {}), src].join('\\0'));
    { const ptr = inst.exports.tsrs_input(req.length); new Uint8Array(mem.buffer).set(req, ptr); }
    const st = inst.exports.tsrs_transpile();
    const out = Buffer.from(mem.buffer, inst.exports.tsrs_output(), inst.exports.tsrs_output_len()).toString();
    if (st === 0) return { outputText: out, sourceMapText: Buffer.from(mem.buffer, inst.exports.tsrs_map(), inst.exports.tsrs_map_len()).toString(), diagnostics: [] };
    const i = out.indexOf('\\0');
    if (i < 0) throw new Error('tsrs transpile: ' + out);
    return { outputText: out.slice(i + 1), diagnostics: out.slice(0, i).split('\\n').map((m) => ({ messageText: m, category: 1 })) };
  }
  const api = {
    transpileModule(src, opts) {
      opts = opts || {};
      const r = run(opts.fileName || '', opts.compilerOptions, src);
      if (r.sourceMapText === '') delete r.sourceMapText;
      return r;
    },
    transpile(src, compilerOptions, fileName) { return run(fileName || '', compilerOptions, src).outputText; },
  };
  const t = (global.transpiler = global.transpiler || {});
  Object.defineProperty(t, 'typescript', { value: api, writable: true, configurable: true, enumerable: true });
})();
`;
fs.writeFileSync(out, code);
console.log('wrote', out, 'wasm raw', fs.statSync(wasmPath).size, 'brotli', br.length, 'shim bytes', code.length);
